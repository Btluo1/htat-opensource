const translations = { 'zh-CN': zhCN, en };

let currentLang = localStorage.getItem('Tdb_lang') || getBrowserLanguage();
let observer = null;

function getBrowserLanguage() {
  const browserLang = navigator.language || navigator.userLanguage || 'zh-CN';
  if (SUPPORTED_LANGUAGES.some(lang => lang.code === browserLang)) return browserLang;
  const mainLang = browserLang.split('-')[0];
  const match = SUPPORTED_LANGUAGES.find(lang => lang.code.split('-')[0] === mainLang);
  return match ? match.code : 'zh-CN';
}

function getLanguageFallbacks(langCode) {
  const baseLang = String(langCode || '').split('-')[0];
  if (baseLang === 'zh') return [...new Set([langCode, 'zh-CN', 'en'].filter(Boolean))];
  return [...new Set([langCode, baseLang, 'en', 'zh-CN'].filter(Boolean))];
}

function t(key) {
  for (const langCode of getLanguageFallbacks(currentLang)) {
    const value = translations[langCode]?.[key];
    if (value !== undefined && value !== null) return value;
  }
  return key;
}

function setLanguage(langCode) {
  const lang = getLanguageConfig(langCode);
  if (!lang) return false;
  currentLang = lang.code;
  localStorage.setItem('Tdb_lang', currentLang);
  initLanguage();
  updateAllI18nElements();
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: currentLang } }));
  return true;
}

function updateAllI18nElements(root = document) {
  if (!root?.querySelectorAll) return;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const text = t(el.getAttribute('data-i18n'));
    if (el.innerHTML !== text) el.innerHTML = text;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
}

function updateDOM(el) {
  if (!el) return;
  updateAllI18nElements(el);
}

function getCurrentLanguage() {
  return currentLang;
}

function getLanguageConfig(langCode) {
  return SUPPORTED_LANGUAGES.find(lang => lang.code === langCode);
}

function getSupportedLanguages() {
  return SUPPORTED_LANGUAGES;
}

function initLanguage() {
  const lang = getLanguageConfig(currentLang) || getLanguageConfig('zh-CN');
  currentLang = lang.code;
  document.documentElement.dir = lang.dir;
  document.documentElement.lang = lang.code;
}

function initI18n() {
  updateAllI18nElements();
  if (observer) observer.disconnect();
  if (!document.body || typeof MutationObserver === 'undefined') return;
  observer = new MutationObserver(mutations => {
    for (const mutation of mutations) {
      if (mutation.type !== 'childList') continue;
      for (const node of mutation.addedNodes) {
        if (node.nodeType === Node.ELEMENT_NODE) updateAllI18nElements(node);
      }
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

window.i18n = {
  t,
  setLanguage,
  getCurrentLanguage,
  getLanguageConfig,
  getSupportedLanguages,
  initLanguage,
  initI18n,
  updateDOM,
  updateAllI18nElements,
};
